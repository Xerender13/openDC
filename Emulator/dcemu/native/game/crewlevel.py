"""2016 client: crew level, crew EXP, crew research, the team item shop, the crew introduction and the two crew boards
(new since 2011; the 2011 client has none of these messages). Read from the 2016 exe by a delegated worker (session 42;
its addresses below), the tables are the client's own Init/TeamResearchTable.xlt and Init/TeamLevelExpBuffTable.xlt
(the client loads both itself: window 0x674510).

Crew record (XiStrTeamInfo 664, crews.info_bytes) new fields: +0x180 char[256] the introduction (four lines joined
with "\\n"; 0x6798c3), +0x284 i64 crew EXP (level bar 0x678a5d), +0x28c u32 crew level (buff rows 0x674bc0: an index
into TeamLevelExpBuffTable), +0x290 i64 a number shown with "%I64d" in the contribution panel (0x676475; here the
Team Research Points: *a guess*). 0x349 after the record: u16 age @0x2aa, u32 @0x2ac (the EXP number of the level
panel, 0x678a00), u32 @0x2b0 (-> player +0x1d6c, not seen used). Act 0x407 refreshes the level panel (0x546496).

C>S 0xce5 (0x10a; 0x868d60): u32 crew id low @2, high @6, char[256] the introduction @0xa -> stored (master only),
    0x349 act 0x407 to the crew.
C>S 0xce6 (0x12; 0x868e10): u32 selector @2 (0 / 1), u32 board @6 (0x409 / 0x408), u32 page @0xa (0-based), u32 rows
    per page @0xe (10) -> S>C 0xce7 (handler 0x547b40; header 0x18: selector, board, page, rows, i32 total @0x12,
    u16 n @0x16; n x 0x14a entries: 53 unread bytes, wchar text @0x35, u32 time_t @0x146). Board 0x408 also puts
    page 0's first seven texts in a news box. Here: 0x408 = the crew's news (research started / finished, level
    ups: ours), 0x409 = members' activity (joins / leaves are not logged yet: empty).
C>S 0xce8 (6; 0x868ec0): u32 0 -> S>C 0xce9 (handler 0x547bb0; u32 @2 unread, u16 n @6, n x 0x48 entries: wchar[32]
    research id, i64 time: 0 = available, a future time_t = in progress (the finish time), past = done; the client
    sorts them into its three lists 0x677430; ids not in its table must not be sent).
C>S 0xcea (0x46; 0x868f50): u32 0, wchar[32] research id -> start it (confirm text 12844: "Use <n> Team Research
    Point"); the client does not check the rank: the server allows the master only.
C>S 0xcec (0x46; 0x868ff0): u32 0, wchar[32] the id of a finished research -> buy its item in the "Team Exclusive
    Item Shop" (12845: "Cost: <price> Team Contribution Point").
C>S 0xceb (0x12; 0x869090): a donation (kind, amounts): donate() (Mito only; a reading, not proven in game).
C>S 0xce4 (0x34; 0x868ca0): the 2016 create-crew request: crews.create_team_2016.

Rules (texts from the client; the amounts that are not in a text are ours):
- "1% of acquired EXP of team members will be accumulated to gain team Lv." (12725): progress.add_exp -> gain().
  The crew level is the TeamLevelExpBuffTable row whose cumulative EXP (column 3) the crew EXP has reached.
- Team Research Points: ours: each crew EXP point gained is also a research point; and 12838 "1 point per 100 Mito
  contribution" (0xceb kind 1, donate()).
- Team Contribution Points of a member: "distribute 1,000 Team Exp ... to receive 1 Contribution Point" (12833):
  the member's contributed crew EXP / 1000, less what the member spent in the team shop.
- A research: master only, crew level >= req level, req tech done, none running, req point paid; it ends after
  "research time (s)"; then its item can be bought by any member for "price" contribution points: the row's itemid
  (a drift item, VisualItem passive_*) for count/period days (driftuse.give, SkidItem).
"""
import os
import struct

from ...handlers import on
from ...protocol import C2S
from ...wire import Frame
from .. import context, now
from .login import SVC, error, send
from .records import wstr

TABLES_SQL = (
    """CREATE TABLE IF NOT EXISTS SKID_TEAM2016_TB(SERVERID numeric(18,0) NOT NULL, TID numeric(18,0) NOT NULL,
  TEAMEXP bigint NOT NULL DEFAULT 0, RPOINT bigint NOT NULL DEFAULT 0, NEWS citext NULL, PRIMARY KEY (SERVERID, TID))""",
    """CREATE TABLE IF NOT EXISTS SKID_TEAMRESEARCH_TB(SERVERID numeric(18,0) NOT NULL, TID numeric(18,0) NOT NULL,
  RESEARCHID citext NOT NULL, ENDTIME int NOT NULL, PRIMARY KEY (SERVERID, TID, RESEARCHID))""",
    """CREATE TABLE IF NOT EXISTS SKID_TEAMCONTRIB_TB(SERVERID numeric(18,0) NOT NULL, CID numeric(18,0) NOT NULL,
  TID numeric(18,0) NOT NULL, TEAMEXP bigint NOT NULL DEFAULT 0, SPENT bigint NOT NULL DEFAULT 0,
  PRIMARY KEY (SERVERID, CID, TID))""",
    """CREATE TABLE IF NOT EXISTS SKID_TEAMEVENT_TB(ID bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  SERVERID numeric(18,0) NOT NULL, TID numeric(18,0) NOT NULL, BOARD int NOT NULL, TEXT citext NOT NULL,
  TIME int NOT NULL)""")
ROW_SQL = "SELECT TEAMEXP, RPOINT, NEWS FROM SKID_TEAM2016_TB WHERE SERVERID=%s AND TID=%s"
ENSURE_SQL = "INSERT INTO SKID_TEAM2016_TB(SERVERID, TID, TEAMEXP, RPOINT) VALUES (%s, %s, 0, 0) ON CONFLICT DO NOTHING"
GAIN_SQL = "UPDATE SKID_TEAM2016_TB SET TEAMEXP=TEAMEXP+%s, RPOINT=RPOINT+%s WHERE SERVERID=%s AND TID=%s"
CONTRIB_SQL = ("INSERT INTO SKID_TEAMCONTRIB_TB(SERVERID, CID, TID, TEAMEXP, SPENT) VALUES (%s, %s, %s, %s, %s)"
               " ON CONFLICT (SERVERID, CID, TID) DO UPDATE SET TEAMEXP=SKID_TEAMCONTRIB_TB.TEAMEXP+EXCLUDED.TEAMEXP,"
               " SPENT=SKID_TEAMCONTRIB_TB.SPENT+EXCLUDED.SPENT")
CONTRIB_ROW_SQL = "SELECT TEAMEXP, SPENT FROM SKID_TEAMCONTRIB_TB WHERE SERVERID=%s AND CID=%s AND TID=%s"
NEWS_SQL = "UPDATE SKID_TEAM2016_TB SET NEWS=%s WHERE SERVERID=%s AND TID=%s"
PAY_SQL = "UPDATE SKID_TEAM2016_TB SET RPOINT=RPOINT-%s WHERE SERVERID=%s AND TID=%s AND RPOINT>=%s"
RESEARCH_SQL = "SELECT RESEARCHID, ENDTIME FROM SKID_TEAMRESEARCH_TB WHERE SERVERID=%s AND TID=%s"
START_SQL = "INSERT INTO SKID_TEAMRESEARCH_TB(SERVERID, TID, RESEARCHID, ENDTIME) VALUES (%s, %s, %s, %s)"
EVENT_SQL = "INSERT INTO SKID_TEAMEVENT_TB(SERVERID, TID, BOARD, TEXT, TIME) VALUES (%s, %s, %s, %s, %s)"
EVENTS_SQL = "SELECT TEXT, TIME FROM SKID_TEAMEVENT_TB WHERE SERVERID=%s AND TID=%s AND BOARD=%s ORDER BY ID"

NEWS, ACTIVITY = 0x408, 0x409
EVENT_ENTRY, RESEARCH_ENTRY = 0x14a, 0x48
REFRESH_ACT = 0x407
_ready = False
_research = None
_levels = None


def is_on():
    from ..version import is_2016
    return is_2016()


async def ensure():
    global _ready
    if not _ready:
        for sql in TABLES_SQL:
            await context.db.execute(sql)
        _ready = True


def _int(v, default=0):
    try:
        return int(float(str(v).strip()))
    except (TypeError, ValueError):
        return default


def research_table():
    """TeamResearchTable.xlt -> {researchid: row dict}, in table order."""
    global _research
    if _research is None:
        from ..data import read_xlt
        _research = {}
        path = os.path.join(context.data.root, 'Init', 'TeamResearchTable.xlt')
        if os.path.exists(path):
            for r in read_xlt(path)[3:]:
                if len(r) > 10 and r[1].strip():
                    _research[r[1].strip()] = dict(
                        id=r[1].strip(), item=r[2].strip(), kind=r[3].strip(), count=_int(r[4], 1), desc=r[5].strip(),
                        level=_int(r[6]), point=_int(r[7]), tech='' if r[8].strip() in ('', 'n/a') else r[8].strip(),
                        seconds=_int(r[9]), price=_int(r[10]))
    return _research


def level_table():
    """TeamLevelExpBuffTable.xlt -> [(level, cumulative EXP)] ascending."""
    global _levels
    if _levels is None:
        from ..data import read_xlt
        _levels = []
        path = os.path.join(context.data.root, 'Init', 'TeamLevelExpBuffTable.xlt')
        if os.path.exists(path):
            for r in read_xlt(path)[3:]:
                if len(r) > 3 and r[1].strip().isdigit():
                    _levels.append((int(r[1]), _int(r[3])))
        _levels.sort()
    return _levels


def level_of(exp):
    if exp <= 0:
        return 0
    level = 0
    for lv, total in level_table():
        if exp >= total:
            level = lv
    return level


async def extra(tid):
    """(crew EXP, research points, introduction) of a crew."""
    db = context.db
    await ensure()
    r = await db.row(ROW_SQL, (db.server_id, tid))
    return (_int(r[0]), _int(r[1]), (r[2] or '')) if r else (0, 0, '')


def fill(out, t):
    """The 2016 fields of XiStrTeamInfo (crews.info_bytes) from t['x2016'] = (EXP, points, introduction)."""
    exp, points, news = t.get('x2016', (0, 0, ''))
    out[0x180:0x280] = news.encode('cp949', 'replace')[:255].ljust(256, b'\0')
    struct.pack_into('<qIq', out, 0x284, exp, level_of(exp), points)


async def gain(c, exp):
    """A member gained EXP: 1% to the crew (and as many research points: ours) and to the member's contribution."""
    part = exp // 100
    if not is_on() or part <= 0 or c.team_id <= 0:
        return
    db = context.db
    await ensure()
    old = (await extra(c.team_id))[0]
    await db.execute(ENSURE_SQL, (db.server_id, c.team_id))
    await db.execute(GAIN_SQL, (part, part, db.server_id, c.team_id))
    await db.execute(CONTRIB_SQL, (db.server_id, c.cid, c.team_id, part, 0))
    if level_of(old + part) > level_of(old):
        await event(c.team_id, NEWS, f'The crew reached Team Level {level_of(old + part)}.')
        await refresh_crew(c.team_id)


async def event(tid, board, text):
    db = context.db
    await ensure()
    await db.execute(EVENT_SQL, (db.server_id, tid, board, text[:128], now()))


async def refresh_crew(tid):
    """0x349 act 0x407 (the level panel) to every member online."""
    from .crews import crew_sessions, my_info_frame, refresh
    for s in crew_sessions(tid):
        p = s.state.get('player')
        if p:
            await refresh(s, p)
            send(s, my_info_frame(s, p, REFRESH_ACT))


def crew_of(session):
    p = session.state.get('player')
    return (p, p.char.team_id) if p and p.char.team_id > 0 else (p, 0)


@on(SVC, C2S, 0xce5)
async def set_introduction(session, frame):
    p, tid = crew_of(session)
    if not is_on() or not tid or len(frame.payload) < 8:
        return
    from .crews import MASTER
    if p.char.team_rank != MASTER:
        return error(session, '20084')
    text = frame.payload[8:8 + 256].split(b'\0', 1)[0].decode('cp949', 'replace')
    db = context.db
    await ensure()
    await db.execute(ENSURE_SQL, (db.server_id, tid))
    await db.execute(NEWS_SQL, (text, db.server_id, tid))
    session.log.note(f'crew {tid}: introduction set ({len(text)} chars)')
    await refresh_crew(tid)


@on(SVC, C2S, 0xce6)
async def get_events(session, frame):
    p, tid = crew_of(session)
    if not is_on() or len(frame.payload) < 16:
        return
    selector, board, page, rows = struct.unpack_from('<4I', frame.payload)
    rows = max(min(rows, 50), 1)
    db = context.db
    items = []
    if tid:
        await ensure()
        items = [(r[0] or '', _int(r[1])) for r in await db.rows(EVENTS_SQL, (db.server_id, tid, board))]
    total = len(items)
    part = items[page * rows:(page + 1) * rows]
    body = struct.pack('<IIIIiH', selector, board, page, rows, total, len(part))
    for text, when in part:
        e = bytearray(EVENT_ENTRY)
        t = text.encode('utf-16-le')[:EVENT_ENTRY - 0x35 - 6]
        e[0x35:0x35 + len(t)] = t
        struct.pack_into('<I', e, 0x146, when)
        body += bytes(e)
    send(session, Frame(0xce7, body))


async def researches(tid):
    """{research id: end time} of a crew."""
    db = context.db
    await ensure()
    return {r[0].strip(): _int(r[1]) for r in await db.rows(RESEARCH_SQL, (db.server_id, tid))}


def research_frame(done):
    rows = [(rid, done.get(rid, 0)) for rid in research_table()]
    body = struct.pack('<IH', 0, len(rows))
    for rid, end in rows:
        body += wstr(rid, 64) + struct.pack('<q', end)
    return Frame(0xce9, body)


@on(SVC, C2S, 0xce8)
async def get_research(session, frame):
    p, tid = crew_of(session)
    if not is_on() or not p:
        return
    send(session, research_frame(await researches(tid) if tid else {}))


def id_of(payload):
    return payload[4:4 + 64].decode('utf-16-le', 'replace').split('\0', 1)[0].strip()


@on(SVC, C2S, 0xcea)
async def start_research(session, frame):
    from .crews import MASTER
    p, tid = crew_of(session)
    if not is_on() or not tid or len(frame.payload) < 6:
        return
    rid = id_of(frame.payload)
    row = research_table().get(rid)
    if p.char.team_rank != MASTER:
        return error(session, '20084')
    done = await researches(tid)
    exp, points, _ = await extra(tid)
    t = now()
    why = None
    if not row or rid in done:
        why = 'That research cannot be started.'
    elif any(end > t for end in done.values()):
        why = 'Another research is in progress.'
    elif level_of(exp) < row['level']:
        why = f'Team Level {row["level"]} is needed.'
    elif row['tech'] and not (row['tech'] in done and done[row['tech']] <= t):
        why = 'The research before it must be finished first.'
    if not why:
        db = context.db
        if not await db.execute(PAY_SQL, (row['point'], db.server_id, tid, row['point'])):
            why = f'Not enough Team Research Points ({row["point"]} needed).'
    if why:
        session.log.note(f'crew {tid}: research {rid!r} refused: {why}')
        from .. import admin
        return admin.message(session, why)
    end = t + row['seconds']
    await context.db.execute(START_SQL, (context.db.server_id, tid, rid, end))
    await event(tid, NEWS, f'Research started: {row["desc"]}')
    session.log.note(f'crew {tid}: research {rid!r} started, ends {end}')
    done[rid] = end
    from .crews import crew_sessions
    for s in crew_sessions(tid):
        send(s, research_frame(done))
    await refresh_crew(tid)


async def contribution(c, tid):
    """A member's Team Contribution Points: contributed crew EXP / 1000 (12833) less what was spent."""
    db = context.db
    await ensure()
    r = await db.row(CONTRIB_ROW_SQL, (db.server_id, c.cid, tid))
    return (_int(r[0]) // 1000 - _int(r[1])) if r else 0


@on(SVC, C2S, 0xcec)
async def buy_item(session, frame):
    from .driftuse import Gains, give
    p, tid = crew_of(session)
    if not is_on() or not tid or len(frame.payload) < 6:
        return
    key = id_of(frame.payload)
    row = research_table().get(key) or next((r for r in research_table().values() if r['item'] == key), None)
    done = await researches(tid)
    from .. import admin
    if not row or not (row['id'] in done and done[row['id']] <= now()):
        return admin.message(session, 'That item has not been researched by your crew.')
    have = await contribution(p.char, tid)
    if have < row['price']:
        return admin.message(session, f'Not enough Team Contribution Points ({row["price"]} needed, {have} held).')
    db = context.db
    await db.execute(CONTRIB_SQL, (db.server_id, p.char.cid, tid, 0, row['price']))
    kind = 'SkidItem' if row['kind'].lower() == 'visualitem' else 'NormalItem'
    gains = Gains()
    await give(session, p, [(kind, row['item'], row['count'] if kind == 'SkidItem' else 0,
                             1 if kind == 'SkidItem' else row['count'], 0)], gains)
    gains.send(session, p)
    session.log.note(f'crew {tid}: {p.char.name!r} bought {row["item"]} for {row["price"]} contribution points')


@on(SVC, C2S, 0xceb)
async def donate(session, frame):
    """0xceb (sender 0x869090 from the contribution panel 0x674360, 0x12 bytes): u32 kind @2 (0 / 1, anything else
    sent as 0 amounts), u32 @6, u32 @0xa. The panel's dialogs are 12842 "distribute %d OMD Gold Mark" and 12843
    "distribute %s Mito"; 12838: "Gain 1 point per OMD Gold Mark contribution, 1 point per 100 Mito contribution".
    Ours (worker 6's reading, not proven in game): kind 1 = Mito, the amount = the first non-zero of the two u32;
    Mito taken, amount / 100 Team Research Points to the crew; kind 0 (OMD Gold Mark: no such balance here) logged."""
    from .items import add_money
    from .login import stat_frames
    p, tid = crew_of(session)
    if not is_on() or not tid or len(frame.payload) < 12:
        return
    kind, a, b = struct.unpack_from('<3I', frame.payload)
    amount = a or b
    session.log.note(f'crew {tid}: donation kind {kind}, amounts {a} / {b}')
    if kind != 1 or amount < 100:
        return
    amount -= amount % 100
    if amount > p.char.mito or not await add_money(p.char, -amount):
        return error(session, '20092')
    db = context.db
    await ensure()
    await db.execute(ENSURE_SQL, (db.server_id, tid))
    await db.execute(GAIN_SQL, (0, amount // 100, db.server_id, tid))
    send(session, Frame(0x8a, struct.pack('<iiqq', 1, 1, -amount, p.char.mito) + b'\0\0'))
    for f in stat_frames(p):
        send(session, f)
    await event(tid, NEWS, f'{p.char.name} contributed {amount} Mito.')
    await refresh_crew(tid)
